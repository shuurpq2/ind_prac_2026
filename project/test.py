    M[3] = 9

    assert not MnozhestvoPusto(M) # Вызываем проверяемую функцию (множество пусто) и тут же проверяем ответ
    assert M[1] == 4 and M[2] == 2 and M[3] == 9 # Проверка, остались ли элементы множества неизменны

    print("Множество успешно проверено на пустоту")

