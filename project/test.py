def TestMnozhestvoPusto():
    N = 10
    M = [PROBEL] * (N+1) # Создаем множество длиной N+1 (+1 для возможности индексации от 1 до N)
    M[0] = 0

    assert MnozhestvoPusto(M) # Вызываем проверяемую функцию (множество пусто) и тут же проверяем ответ
    assert len(M) == N+1 # Проверяем, осталась ли длина прежней

    for i in range(1, N+1):
        assert M[i] == PROBEL # Проверка, остались ли элементы множества неизменны

    M[0] = 3 # Заполняем множество элементами 
    M[1] = 4
